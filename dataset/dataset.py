"""
PyTorch Dataset for binary gate segmentation.

Expected directory layout:
    <root>/
        images/   — RGB images  (.png / .jpg / .jpeg)
        masks/    — Binary masks (same stem OR stem with _img→_mask suffix swap)
                    Pixel value 0 = background, any nonzero = gate.

Pairing strategy:
    1. Direct stem match — image "frame_01.png" pairs with mask "frame_01.png".
    2. Suffix-swap match — image "000_00_img.png" pairs with mask "000_00_mask.png".
       Handles datasets generated by the synthetic pipeline in archive/scripts/.

The mask is loaded as a single-channel (L-mode) image and binarized to {0, 1}.
"""

from pathlib import Path
from typing import Callable

import numpy as np
import torch
from PIL import Image
from torch.utils.data import Dataset

_EXTS = {".png", ".jpg", ".jpeg"}


def _pair_images_and_masks(img_dir: Path, mask_dir: Path) -> list[tuple[Path, Path]]:
    """
    Build a list of (image_path, mask_path) pairs.

    Tries direct stem matching first; falls back to replacing a trailing
    '_img' suffix with '_mask' for datasets produced by the synthetic generator.
    """
    mask_by_stem = {p.stem: p for p in mask_dir.glob("*") if p.suffix.lower() in _EXTS}

    pairs = []
    for img_path in sorted(img_dir.glob("*")):
        if img_path.suffix.lower() not in _EXTS:
            continue
        stem = img_path.stem

        if stem in mask_by_stem:                              # direct match
            pairs.append((img_path, mask_by_stem[stem]))
        elif stem.endswith("_img"):                           # suffix-swap match
            mask_stem = stem[: -len("_img")] + "_mask"
            if mask_stem in mask_by_stem:
                pairs.append((img_path, mask_by_stem[mask_stem]))

    return pairs


class GateDataset(Dataset):
    """
    Args:
        img_dir:   Path to the images/ directory.
        mask_dir:  Path to the masks/ directory.
        transform: Optional albumentations Compose applied jointly to image and
                   mask so geometric transforms stay perfectly synchronized.
    """

    def __init__(self, img_dir: str | Path, mask_dir: str | Path, transform: Callable | None = None):
        self.transform = transform

        pairs = _pair_images_and_masks(Path(img_dir), Path(mask_dir))
        if not pairs:
            raise FileNotFoundError(
                f"No matched image/mask pairs found.\n"
                f"  images: {img_dir}\n"
                f"  masks:  {mask_dir}"
            )
        self._img_paths, self._mask_paths = zip(*pairs)

    def __len__(self) -> int:
        return len(self._img_paths)

    def __getitem__(self, idx: int) -> dict:
        img_path  = self._img_paths[idx]
        mask_path = self._mask_paths[idx]

        # Load as numpy arrays — albumentations requires HWC uint8.
        image = np.array(Image.open(img_path).convert("RGB"), dtype=np.uint8)
        mask  = np.array(Image.open(mask_path).convert("L"),  dtype=np.uint8)

        if self.transform:
            out   = self.transform(image=image, mask=mask)
            image = out["image"]
            mask  = out["mask"]

        # Image: (H, W, 3) uint8 → (3, H, W) float32 in [0, 1]
        # Mask:  (H, W)    uint8 → (1, H, W) float32 in {0, 1}
        image = torch.from_numpy(image).permute(2, 0, 1).float() / 255.0
        mask  = torch.from_numpy(mask).unsqueeze(0).float().div(255).gt(0).float()

        return {"image": image, "mask": mask, "id": img_path.stem}
